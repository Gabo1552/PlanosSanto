import { test,expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { PDFDocument } from 'pdf-lib';
import { mkdir,writeFile } from 'node:fs/promises';
import type { Project,RawDocument } from '../../lib/model';
test('el JSON local Ruby de contrato llega al editor con jerarquía/medidas y produce PDF',async({page,request})=>{
  const fixture=await readFile('sketchup/build/contract-fixture.json');
  await page.goto('/');
  const imported=page.waitForResponse(r=>r.url().endsWith('/api/import/file')&&r.request().method()==='POST');
  await page.getByLabel('Archivo del proyecto').setInputFiles({name:'synthetic.planos-santo.json',mimeType:'application/json',buffer:fixture});
  const response=await imported;expect(response.status()).toBe(201);
  const p=(await response.json()).project as Project;
  expect(p.source).toBe('sketchup-ruby');expect(p.furniture).toHaveLength(2);
  await expect(page.getByText('SKETCHUP · EXTENSIÓN RUBY',{exact:true})).toBeVisible();
  await expect(page.locator('tbody tr')).toHaveCount(2);
  await expect(page.locator('tbody')).toContainText('609,6');
  await page.getByRole('textbox',{name:'Nombre P01',exact:true}).fill('Pieza Ruby anotada');
  await page.getByRole('button',{name:'Agregar nota a P01'}).click();
  await page.getByRole('textbox',{name:'Comentario',exact:true}).fill('Nota sobre pieza del contrato Ruby.');
  await page.getByRole('button',{name:'Cancelar',exact:true}).click();
  await page.getByRole('button',{name:'Guardar ahora'}).click();await expect(page.getByRole('status').filter({hasText:'Guardado'})).toBeVisible();
  const saved=await(await request.get(`/api/projects/${p.id}`)).json() as Project;
  expect(saved.importedDocument?.furniture[0].children[1].children[0].metadata?.instancePath).toEqual(['1','13','12']);
  expect(saved.furniture[0].notes[0].pieceId).toBe('1/11');
  await page.reload();await page.getByLabel('Proyectos guardados').selectOption(saved.id);
  await expect(page.getByTestId('note-box')).toContainText('contrato Ruby');
  const pdf=await request.get(`/api/pdf/${p.id}`);expect(pdf.status()).toBe(200);
  expect((await PDFDocument.load(await pdf.body())).getPageCount()).toBe(2);
  await mkdir('artifacts',{recursive:true});await writeFile('artifacts/ruby-contract-A4.pdf',await pdf.body());
  await page.screenshot({path:'artifacts/ruby-contract-editor.png',fullPage:true});
});
test('el diálogo permite revisar la jerarquía, evita padres/hijos simultáneos y no ejecuta nombres como HTML',async({page})=>{
  const doc=JSON.parse(await readFile('sketchup/build/contract-fixture.json','utf8')) as RawDocument;
  doc.furniture[0].name='<img src=x onerror="window.bad=true">';
  await page.setContent(await readFile('sketchup/planos_santo/review.html','utf8'));
  await page.evaluate(()=>{Object.assign(window,{sketchup:{scan(){},export_local(){},send_web(){}}});});
  await page.evaluate(data=>{
    (window as unknown as {receive:(e:unknown)=>void}).receive({type:'tree',data:{roots:data.furniture,modelName:data.name,warnings:[]}});
  },doc);
  await expect(page.locator('#tree img')).toHaveCount(0);
  expect(await page.evaluate(()=>Boolean((window as unknown as {bad:boolean}).bad))).toBe(false);
  const root=page.locator('[data-id="1"]'),child=page.locator('[data-id="1/11"]');
  await root.check();await expect(page.getByRole('button',{name:'2. Guardar ZIP para la web'})).toBeEnabled();
  await child.check();await expect(root).not.toBeChecked();await expect(child).toBeChecked();
  await page.getByText('Opcional: enviar directamente a la web',{exact:true}).click();
  await expect(page.getByRole('button',{name:'Enviar a Planos Santo',exact:true})).toBeDisabled();
  await page.evaluate(()=>{(window as unknown as {receive:(e:unknown)=>void}).receive({type:'exported',data:{path:'C:/synthetic.json',report:{furniture:[{}],pieces:1,sha256:'test'}}});});
  await page.getByLabel('Verifiqué la exportación local').check();await expect(page.getByRole('button',{name:'Enviar a Planos Santo',exact:true})).toBeEnabled();
  await root.check();await expect(page.getByRole('button',{name:'Enviar a Planos Santo',exact:true})).toBeDisabled();
});
