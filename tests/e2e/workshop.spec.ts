  await expect(page.locator('[data-label]')).toHaveCount(6);
  await page.getByRole('button',{name:'Ver exterior',exact:true}).click();
  await page.getByRole('textbox',{name:'Nombre P01',exact:true}).fill('Costado marcado – prueba');
  await expect(page.locator('tbody tr').first()).toContainText('700');
  await page.getByRole('button',{name:'Agregar nota a P01'}).click();
  await page.getByRole('textbox',{name:'Comentario',exact:true}).fill('Usar tarugos de 8 mm. No perforar de lado a lado.');
  // Pick a surface point to record an actual local 3D anchor.
  const poly=page.locator('[data-piece="m-lateral-izq"]').first();
  const polyCenter=await poly.evaluate(el=>{const box=(el as unknown as SVGGraphicsElement).getBBox();const p=(el as unknown as SVGElement).ownerSVGElement!.createSVGPoint();p.x=box.x+box.width/2;p.y=box.y+box.height/2;const q=p.matrixTransform((el as unknown as SVGGraphicsElement).getScreenCTM()!);return {x:q.x,y:q.y};});
