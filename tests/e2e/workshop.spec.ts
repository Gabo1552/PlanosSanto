  expect(textMetrics.length).toBe(2);expect(textMetrics.every(m=>m.size>=7&&m.bounds<=190)).toBe(true);
  const point=await page.locator('.sheet').first().boundingBox();
  await page.setViewportSize({width:1650,height:1200});await page.screenshot({path:'artifacts/print-A4.png',fullPage:true});
  expect(point!.width).toBeCloseTo(297/25.4*96,0);
  await page.goto('/');await page.getByLabel('Proyectos guardados').selectOption(project.id);
  await page.getByText('Usar tarugos de 8 mm. No perforar de lado a lado.',{exact:true}).first().click();
  await page.getByRole('button',{name:'Eliminar nota',exact:true}).click();
  await expect(page.getByTestId('note-box')).toHaveCount(0);
