  await page.getByRole('button',{name:'Guardar ahora'}).click();
  await expect(page.getByRole('status').filter({hasText:'Guardado'})).toBeVisible();
  stored=await (await request.get(`/api/projects/${project.id}`)).json() as Project;
  expect(stored.furniture[0].notes[0].position).not.toEqual(note.position);
